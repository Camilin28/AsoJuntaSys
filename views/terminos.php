<h1>TÉRMINOS Y CONDICIONES DE USO</h1>
<h2>Portal Web AsoJuntaSys</h2>

<p>
El presente documento establece los términos y condiciones que regulan el acceso y uso del portal web 
<strong>AsoJuntaSys</strong>, plataforma digital diseñada para fortalecer la gestión administrativa 
de las Juntas de Acción Comunal (JAC) del municipio de Arbeláez, Cundinamarca.
</p>

<h3>1. Aceptación de los términos</h3>
<p>
Al registrarse o iniciar sesión en la plataforma, el usuario declara haber leído, entendido y aceptado 
los presentes términos y condiciones, así como la política de tratamiento de datos personales.
</p>

<h3>2. Finalidad del sistema</h3>
<p>
AsoJuntaSys tiene como finalidad optimizar la gestión documental, administrativa y financiera 
de las Juntas de Acción Comunal, promoviendo la transparencia, eficiencia y participación ciudadana.
</p>

<h3>3. Usuarios autorizados</h3>
<p>
El acceso al sistema está restringido a usuarios autorizados, tales como Presidente General, 
Presidentes de JAC, Secretaría y Tesorería. Cada usuario es responsable del uso adecuado 
de sus credenciales de acceso.
</p>

<h3>4. Protección de datos personales</h3>
<p>
El tratamiento de los datos personales se realizará conforme a lo establecido en la 
Ley 1581 de 2012 y el Decreto 1377 de 2013. 
La información recolectada será utilizada exclusivamente para fines administrativos y de gestión comunitaria.
</p>

<p>
AsoJuntaSys garantiza la confidencialidad, integridad y disponibilidad de la información 
mediante mecanismos de seguridad como cifrado de contraseñas y control de roles.
</p>

<h3>5. Responsabilidad del usuario</h3>
<p>
El usuario se compromete a:
<ul>
    <li>Proporcionar información veraz y actualizada.</li>
    <li>No compartir sus credenciales de acceso.</li>
    <li>No utilizar la plataforma para fines indebidos o ilegales.</li>
</ul>
</p>

<h3>6. Seguridad de la información</h3>
<p>
La plataforma implementa medidas técnicas y administrativas para proteger la información almacenada. 
Sin embargo, el usuario reconoce que ningún sistema informático es completamente infalible.
</p>

<h3>7. Modificaciones</h3>
<p>
AsoJuntaSys podrá actualizar estos términos cuando sea necesario para mejorar el servicio 
o cumplir con nuevas disposiciones legales.
</p>

<h3>8. Vigencia</h3>
<p>
Los presentes términos entran en vigencia desde el momento de su publicación en la plataforma.
</p>

