<h2>Términos y Condiciones de Uso - AsoJuntaSys</h2>

<p>
El portal AsoJuntaSys es una plataforma digital diseñada para fortalecer la gestión 
administrativa de las Juntas de Acción Comunal del municipio de Arbeláez.
</p>

<h3>1. Uso del sistema</h3>
<p>
El acceso al sistema está restringido a usuarios autorizados (Presidente General,
Presidentes de JAC, Secretaría y Tesorería).
</p>

<h3>2. Protección de datos</h3>
<p>
La información personal almacenada en el sistema será tratada conforme a la 
Ley 1581 de 2012 y el Decreto 1377 de 2013, garantizando confidencialidad,
integridad y disponibilidad.
</p>

<h3>3. Responsabilidad del usuario</h3>
<p>
El usuario es responsable del uso adecuado de su cuenta y de mantener la 
confidencialidad de su contraseña.
</p>

<h3>4. Seguridad</h3>
<p>
AsoJuntaSys implementa mecanismos de cifrado de contraseñas y control de roles.
</p>

